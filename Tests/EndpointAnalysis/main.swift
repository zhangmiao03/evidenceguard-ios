import Foundation
let decoder = JSONDecoder()
func decode<T: Decodable>(_ type: T.Type, _ json: String) throws -> T { try decoder.decode(type, from: Data(json.utf8)) }
let legacy = try decode(EndpointVisionConfiguration.self, #"{"ready":true}"#)
precondition(!legacy.canUseDepth && !legacy.canSampleFresh)
let depthOnly = try decode(EndpointVisionConfiguration.self, #"{"ready":true,"depthEnabled":true,"supportedConditions":["B","C"]}"#)
precondition(depthOnly.canUseDepth && !depthOnly.canSampleFresh)
let ready = try decode(EndpointVisionConfiguration.self, #"{"ready":true,"depthEnabled":true,"supportedConditions":["B","C"],"freshSamplingSupported":true}"#)
precondition(ready.canSampleFresh)
let disabled = try decode(EndpointVisionConfiguration.self, #"{"ready":false,"depthEnabled":true,"supportedConditions":["B","C"],"freshSamplingSupported":true}"#)
precondition(!disabled.canSampleFresh)
let old = try decode(EndpointAnalysis.self, #"{"status":"unknown","reason":"只有一张画面","limitation":"仅作核对"}"#)
precondition(old.depthSummary == nil && old.flowSummary == nil)
let completed = try decode(EndpointAnalysis.self, #"{"status":"completed","condition":"C","limitation":"仅作核对","analysis":{"summary":"杯子仍在桌面"},"auxiliary":{"status":"completed","depth":{"status":"completed"},"flow":{"status":"skipped","code":"FRAMES_NOT_ADJACENT"}}}"#)
precondition(completed.depthSummary!.contains("不能测量实际距离"))
precondition(completed.flowSummary!.contains("未分析连续变化"))
let unreliable = try decode(EndpointAnalysis.self, #"{"status":"completed","limitation":"仅作核对","auxiliary":{"flow":{"status":"completed","quality":"unreliable_for_object_motion"}}}"#)
precondition(unreliable.flowSummary == "画面变化分析未形成可靠判断。")
precondition(ChatPresentation.action("sample_camera_vision") == "取新画面并分析")
print("PASS: old-server capability gates, explicit fresh sampling, and honest depth/flow results")
